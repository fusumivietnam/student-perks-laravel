#!/usr/bin/env node
// GitHub-only deterministic roadmap renderer. Node >= 20, zero npm dependencies.
const fs = require('node:fs');
const owner = process.env.GITHUB_REPOSITORY?.split('/')[0] || 'fusumivietnam';
const name = process.env.GITHUB_REPOSITORY?.split('/')[1] || 'student-perks-laravel';
const token = process.env.GITHUB_TOKEN;
if (!token) throw new Error('GITHUB_TOKEN is required; never write unverified roadmap data');
const origin = 'https://api.github.com';
async function get(path) {
  const r = await fetch(origin + path, {
    headers: { Authorization: 'Bearer ' + token, Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28', 'User-Agent': 'student-perks-roadmap' }
  });
  if (!r.ok) throw new Error('GitHub API error ' + r.status + ' at ' + path);
  return r.json();
}
async function pages(path) {
  const output = [];
  for (let page = 1; page <= 20; page++) {
    const batch = await get(path + (path.includes('?') ? '&' : '?') + 'per_page=100&page=' + page);
    if (!Array.isArray(batch)) throw new Error('Expected array from ' + path);
    output.push(...batch);
    if (batch.length < 100) return output;
  }
  throw new Error('Pagination limit reached: ' + path);
}
const idMatch = title => /^\[(M[0-4])\]\s/.exec(title || '')?.[1];
const issueRef = issue => issue ? '[#' + issue.number + '](' + issue.html_url + ')' : 'MISSING ISSUE';
const canonical = [
  ['M0', 'Laravel 13 + Docker + PostgreSQL 18', 'Framework on main; PostgreSQL migrations/tests, Docker build and HTTP smoke green'],
  ['M1', 'Data model + Filament CMS', 'Brands, categories, offers; migrations, admin CRUD, policies and tests'],
  ['M2', 'Public website and discovery', 'Home, offers, brands/categories, filtering/search and responsive acceptance'],
  ['M3', 'Editorial and SEO', 'Articles/pages, images, metadata, sitemap and safe partner links'],
  ['M4', 'VPS production launch', 'TLS, secrets, persistent storage, backup/restore, smoke/rollback verified']
];
(async () => {
  const root = '/repos/' + owner + '/' + name;
  const [issuesRaw, pullRequests] = await Promise.all([
    pages(root + '/issues?state=all'),
    pages(root + '/pulls?state=all')
  ]);
  const issues = issuesRaw.filter(x => !x.pull_request);
  const lines = [
    '# Student Perks Hub — canonical roadmap',
    '',
    '> **AUTOGENERATED. Do not manually edit this file.** This is the sole roadmap/status view, rendered from GitHub milestone Issues and Pull Requests via [roadmap-sync workflow](../.github/workflows/roadmap-sync.yml). Acceptance gates are versioned in [the renderer](../scripts/sync-roadmap.cjs).',
    '',
    '| ID | Milestone | Acceptance gate | GitHub issue | Status | Linked PRs |',
    '|---|---|---|---|---|---|'
  ];
  let blocked = [];
  for (const [id, title, gate] of canonical) {
    const matches = issues.filter(issue => idMatch(issue.title) === id && issue.labels.some(l => l.name === 'roadmap:milestone'));
    if (matches.length !== 1) throw new Error('Expected exactly one milestone issue for ' + id + ', found ' + matches.length);
    const issue = matches[0];
    const labels = new Set(issue.labels.map(l => l.name));
    const linked = pullRequests.filter(pr => {
      const body = pr.body || '';
      const issuePattern = new RegExp('(?:#|issues/)'+issue.number+'(?![0-9])');
      const milestonePattern = new RegExp('\\b' + id + '\\b');
      return issuePattern.test(body) || milestonePattern.test(pr.title || '') || milestonePattern.test(body);
    });
    const open = linked.some(pr => pr.state === 'open');
    const merged = linked.some(pr => pr.merged_at);
    let status = 'NOT STARTED';
    if (labels.has('roadmap:deferred')) status = 'DEFERRED';
    else if (issue.state === 'closed') status = labels.has('roadmap:accepted') && merged ? 'DONE' : 'BLOCKED — closed without accepted merged PR';
    else if (labels.has('roadmap:blocked')) status = 'BLOCKED';
    else if (open || merged || labels.has('roadmap:in-progress')) status = 'IN PROGRESS';
    const evidence = linked.slice(0, 6).map(pr => '[#' + pr.number + '](' + pr.html_url + ')' + (pr.merged_at ? ' merged' : '')).join(', ') || '—';
    if (status.startsWith('BLOCKED')) blocked.push(id + ': ' + issue.html_url);
    lines.push('| ' + id + ' | ' + title + ' | ' + gate + ' | ' + issueRef(issue) + ' | **' + status + '** | ' + evidence + ' |');
  }
  lines.push('', '## Next execution gate', '');
  lines.push(blocked.length ? 'Resolve the earliest blocked milestone: ' + blocked[0] : 'Proceed with the first not-DONE milestone shown above.');
  lines.push('', '## Integrity and status rules', '');
  lines.push('- Issues with label `roadmap:milestone` and a unique `[M0]`–`[M4]` title are the source records.');
  lines.push('- Open linked PR or merged PR without accepted closure → IN PROGRESS; `roadmap:blocked` → BLOCKED; `roadmap:deferred` → DEFERRED.');
  lines.push('- DONE requires a **closed milestone issue**, `roadmap:accepted` label and at least one **merged linked PR**. The person granting acceptance must verify the defined tests/criteria. The workflow cannot independently certify production.');
  lines.push('- Duplicate/missing milestone issues or GitHub API errors fail the workflow without changing the roadmap.');
  lines.push('- Commits, test evidence, actual deployment and application behavior remain independently verifiable on GitHub; status is not proof that production works.');
  lines.push('', 'Last synchronized automatically from GitHub Issues and PRs. No separate chat or planning roadmap.');
  fs.writeFileSync('docs/ROADMAP.md', lines.join('\n') + '\n');
})().catch(e => { console.error(e); process.exitCode = 1; });
